  function hash(str) { let h = 1779033703 ^ str.length; for (let i = 0; i < str.length; i++) { h = Math.imul(h ^ str.charCodeAt(i), 3432918353); h = (h << 13) | (h >>> 19); } return () => { h = Math.imul(h ^ (h >>> 16), 2246822507); h = Math.imul(h ^ (h >>> 13), 3266489909); return (h ^= h >>> 16) >>> 0; }; }
  function rng(str) { let a = hash(str)(); return () => { a |= 0; a = (a + 0x6d2b79f5) | 0; let t = Math.imul(a ^ (a >>> 15), 1 | a); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }; }
  const shuffle = (R, arr) => { const a = arr.slice(); for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(R() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; };

  // 1問の組を選ぶ：pool のできごとから、難しさの決まりに合う枚数を。avoid の id は使わない。作れなければ null
  function pickSet(R, lv, pool, avoid) {
    const [n, gap, win] = Array.isArray(lv) ? lv : RULE[lv], cand = pool.filter((e) => !avoid.has(e.id));
    for (let t = 0; t < 40; t++) {
      let base = cand;
      if (win) { const a = cand[Math.floor(R() * cand.length)]; if (!a) return null; base = cand.filter((e) => e.y >= a.y && e.y <= a.y + win); }
      const out = [];
      for (const e of shuffle(R, base)) { if (out.every((o) => Math.abs(o.y - e.y) >= gap)) out.push(e); if (out.length === n) break; }
      if (out.length === n) return out;
    }
    return null;
  }
  // 問題のしるし：「難しさ|id.id.id」。並べて見せる順は、しるしから決まる（同じしるしなら同じ順）
  const tagOf = (lv, set) => lv + "|" + set.map((e) => e.id).join(".");
  function make(tag) {
    const [lvs, ids] = String(tag).split("|"), lv = +lvs, set = (ids || "").split(".").map((id) => BY[id]);
    if (!(lv >= 0 && lv <= 3) || set.length < 2 || set.some((e) => !e)) return null;
    const order = set.slice().sort((a, b) => a.y - b.y || a.n - b.n);
    let shown = shuffle(rng("s" + tag), set);
    if (shown.every((e, i) => e === order[i])) shown = shown.slice(1).concat(shown[0]); // はじめから正しい順には並べない
    return { tag, lv, order, shown };
  }
  const keyOf = (tag) => String(tag).split("|")[1].split(".").slice().sort().join(".");

  // 日の問題に使うできごと：足した日より前のものだけ（あとからできごとを足しても、過去の日の問題が変わらない）
  const CUT = {}; // id → この日から日の問題に使う（"YYYY-MM-DD"）。はじめの137件は無し（いつでも使う）
  const poolFor = (date) => EV.filter((e) => !CUT[e.id] || CUT[e.id] <= date);
  // 今日の5問：やさしい2・ふつう2・むずかしい1。同じ日の中では同じできごとを使わない
  function dailyTags(date) {
    const R = rng("d" + date), pool = poolFor(date), used = new Set(), out = [];
    for (const lv of [0, 0, 1, 1, 2]) { const s = pickSet(R, lv, pool, used); s.forEach((e) => used.add(e.id)); out.push(tagOf(lv, s)); }
    return out;
  }
  // 上級：5枚・近い年どうし・3問。今日の5問のできごとと重ねない
  function hardTags(date) {
    const R = rng("h" + date), pool = poolFor(date), used = new Set();
    for (const t of dailyTags(date)) t.split("|")[1].split(".").forEach((id) => used.add(id));
    const out = [];
    for (let i = 0; i < 3; i++) { const s = pickSet(R, 3, pool, used); s.forEach((e) => used.add(e.id)); out.push(tagOf(3, s)); }
    return out;
  }
  // 練習・とことん：R は画面から渡す乱数。avoid の id は使わない（直前の問題と同じできごとを続けない）
  function randomTag(R, lv, avoid, group) {
    if (group == null) { const s = pickSet(R, lv, EV, avoid || new Set()) || pickSet(R, lv, EV, new Set()); return s ? tagOf(lv, s) : null; }
    const pool = EV.filter((e) => ERA[e.era].g === group), s = pickSet(R, ERA_RULE, pool, avoid || new Set()) || pickSet(R, ERA_RULE, pool, new Set()); // 時代の練習は、同じ時代の4枚（年がちがえばよい）
    return s ? tagOf(2, s) : null;
  }
  const sayOf = (e) => `${e.t}`;
  const eraName = (e) => ERA[e.era].name;
  const api = { ERAS, GROUPS, EV, BY, ERA, LV, RULE, rng, shuffle, pickSet, make, keyOf, tagOf, dailyTags, hardTags, randomTag, sayOf, eraName, CUT, poolFor };
  if (typeof module !== "undefined" && module.exports) module.exports = api; else root.REKISHI = api;
